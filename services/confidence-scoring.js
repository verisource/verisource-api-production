/**
 * Determine if image is AI-generated vs AI-enhanced
 */
function categorizeAIContent(metadata, aiConfidence, cameraVerification) {
  const result = { verdict: 'VERIFIED IMAGE', category: null, software: null, softwareType: null, explanation: null };
  
  const aiGenerator = checkForAISoftwareInExif(metadata);
  if (aiGenerator) {
    return { ...result, verdict: 'AI-GENERATED IMAGE', category: 'synthetic', software: aiGenerator, explanation: `Generated by ${aiGenerator}` };
  }
  
  const editingSoftware = checkForEditingSoftwareInExif(metadata);
  const softwareName = editingSoftware?.name;
  const softwareType = editingSoftware?.type;
  
  if (aiConfidence >= 40) {
    const hasRealCamera = cameraVerification?.camera_found && cameraVerification?.is_valid;
    
    if (hasRealCamera && editingSoftware) {
      return { ...result, verdict: softwareType === 'ai' ? 'AI-ENHANCED IMAGE' : 'EDITED IMAGE', category: softwareType === 'ai' ? 'ai-enhanced' : 'edited', software: softwareName, softwareType, explanation: `Real photo edited with ${softwareName}` };
    }
    if (editingSoftware && aiConfidence < 70) {
      return { ...result, verdict: softwareType === 'ai' ? 'AI-ENHANCED IMAGE' : 'EDITED IMAGE', category: softwareType === 'ai' ? 'ai-enhanced' : 'edited', software: softwareName, softwareType, explanation: `Appears edited with ${softwareName}` };
    }
    if (aiConfidence >= 70 && !hasRealCamera) {
      return { ...result, verdict: 'AI-GENERATED IMAGE', category: 'synthetic', explanation: 'High AI indicators, no camera origin detected' };
    }
  }
  
  if (editingSoftware) {
    return { ...result, verdict: softwareType === 'ai' ? 'AI-ENHANCED IMAGE' : 'EDITED IMAGE', category: softwareType === 'ai' ? 'ai-enhanced' : 'edited', software: softwareName, softwareType, explanation: `Edited with ${softwareName}` };
  }
  
  return result;
}

